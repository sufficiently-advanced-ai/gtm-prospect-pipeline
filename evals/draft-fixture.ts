// ---------------------------------------------------------------------------
// Staging path guard — mirrors dataPath()'s escape check, in the other direction.
// ---------------------------------------------------------------------------
function stagingPath(...parts: string[]): string {
  const p = resolve(STAGING_ROOT, ...parts);
  if (p !== STAGING_ROOT && !p.startsWith(STAGING_ROOT + sep))
    throw new Error(`refusing to write outside staging/: ${join(...parts)}`);
  return p;
}

// ---------------------------------------------------------------------------
// Hygiene: redaction (SCHEMA.md — "No secrets, no contact emails, no contact/sequence ids,
// no phone numbers"). Applied to EVERY staged byte, after structural trimming, regardless
// of file type.
// ---------------------------------------------------------------------------
const REDACTED = "<redacted>";

// A redaction must never begin or end inside a JSON escape sequence: a description reading
// `professional:\ncontact@…` once had its email pattern start at the escape's `n` (a `\b`
// holds there — `\` is not a word char), producing `professional:\<redacted>` and an
// unparseable staged JSON file.
//
// Two defences, chosen so the strong one covers every JSON byte:
//   1. JSON inputs are NEVER regex-redacted as serialized text. They are parsed, every
//      string VALUE is redacted in DECODED form (where `\n` is a real newline that no
//      pattern can match into), and re-serialized with JSON.stringify — escapes are
//      regenerated by the serializer, never edited. Structure is preserved exactly;
//      only string values change. (`redactJson()` below; used by every JSON stager.)
//   2. Non-JSON text keeps regex redaction, anchored by ESC_B: a match may start
//      immediately AFTER a two-character escape but never ON its escaped letter. This
//      covers markdown captures that embed JSON blobs.
const ESC_B = String.raw`(?:(?<=\\[nrtbfv])|\b(?<!\\))`;

const REDACTORS: Array<{ label: string; re: RegExp }> = [
  // emails (incl. the "mailto:" wrapper form)
  { label: "mailto: URL", re: new RegExp(ESC_B + String.raw`mailto:[^\s"'<>)\]]+`, "gi") },
  { label: "email address", re: new RegExp(ESC_B + String.raw`[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}\b`, "g") },
  // Apollo/Mongo-style 24-hex object ids (contact ids, sequence ids, org ids)
  { label: "24-hex object id", re: new RegExp(ESC_B + String.raw`[0-9a-f]{24}\b`, "g") },
  // E.164 phone numbers
  { label: "E.164 phone", re: /\+\d{10,15}\b/g },
  // NANP-ish phone numbers: (760) 736-2000 / 760-736-2000 / 760.736.2000
  { label: "NANP phone", re: /(?<![\\\d])\(?\b\d{3}\)?[\s.\-]\d{3}[\s.\-]\d{4}\b/g },
];

function redact(text: string): { text: string; hits: Record<string, number> } {
  const hits: Record<string, number> = {};
  let out = text;
  for (const { label, re } of REDACTORS) {
    const found = out.match(re);
    if (found?.length) hits[label] = (hits[label] ?? 0) + found.length;
    out = out.replace(re, REDACTED);
  }
  return { text: out, hits };
}

// Redact a PARSED JSON value: walk it, redact each decoded string, leave structure (and
// keys) alone. The caller re-serializes — so an escape sequence can never be corrupted.
function redactJson(value: unknown): { value: unknown; hits: Record<string, number> } {
  const hits: Record<string, number> = {};
  const walk = (v: unknown): unknown => {
    if (typeof v === "string") {
      const r = redact(v);
      for (const [k, n] of Object.entries(r.hits)) hits[k] = (hits[k] ?? 0) + n;
      return r.text;
    }
    if (Array.isArray(v)) return v.map(walk);
    if (v && typeof v === "object") {
      const out: Record<string, unknown> = {};
      for (const [k, val] of Object.entries(v as Record<string, unknown>)) out[k] = walk(val);
      return out;
    }
    return v;
  };
  return { value: walk(value), hits };
}

// Serialize + redact in the safe order, for every JSON input staged.
const jsonBytes = (value: unknown): { text: string; hits: Record<string, number> } => {
  const r = redactJson(value);
  return { text: JSON.stringify(r.value, null, 2) + "\n", hits: r.hits };
};

// ---------------------------------------------------------------------------
// Hygiene: gold leakage. Analyst-authored markdown (Sales Navigator notes, posting
// captures, queue checklists) carries the conclusion next to the findings.
// Findings stay, conclusions go — at section, block, and sentence granularity.
//
// Scraped/summarized captures get the SAME detection (they are not innocent: a
// summarized homepage routinely ends "Keep (operating company).", a "## Verdict / DROP —
// staffing agency" section, or a "CONCLUSION: …" line), but a narrower section-header
// list — an "## Assessment" heading on a company's own page is the company's words, an
// "## Verdict" heading never is.
// ---------------------------------------------------------------------------
type StripMode = "analyst" | "scraped";

const CONCLUSION_HEADER =
  /\b(verdict|conclusion|outcome|determination|correction|assessment|decision|recommendation|route|disposition|judgement|judgment)\b/i;

// Scraped sources: only headings that cannot be the source's own voice.
const CONCLUSION_HEADER_SCRAPED = /\b(verdict|conclusion|determination|disposition|judgement|judgment)\b/i;

const CONCLUSION_BLOCK_LEAD =
  /^\s*(?:[-*]\s*)?(?:\*\*)?(VERDICT|CORRECTION|ROUTE|RECOMMENDATION|DECISION|CONCLUSION|ASSESSMENT|DETERMINATION|OUTCOME)\b/i;

const CONCLUSION_SENTENCE: RegExp[] = [
  /\b(SKIP|FLAGGED|DROPPED)\b/,                 // route vocabulary (case-sensitive)
  /\broute\s*:\s*QUALIFIED\b/,
  /\bprovisional[_ ]route\b/i,
  /\bdrop[_ ]class\b/i,
  /\bverdict\b/i,
  /\bdisqualif/i,
  /\brout(?:e|ed)\s+(?:out|to)\b/i,
  /\bfalse[-_ ]positive/i,
  // Verdict lines that lead a scraped summary's last paragraph:
  //   "VERDICT: vendor → DROP", "CONCLUSION: …", "Verdict input: …"
  /^\s*(?:[-*>]\s*)?(?:\*\*)?\s*(VERDICT|CONCLUSION|ASSESSMENT|DETERMINATION|OUTCOME|DECISION|RECOMMENDATION|DISPOSITION)\b(?:\s+input)?\s*(?:\*\*)?\s*[:\-—–]/i,
  // Trailing keep/drop calls: "KEEP.", "DROP — staffing/recruiting agency",
  // "Keep (operating company).", "DROP: vendor — they ARE the capability."
  /^\s*(?:[-*>]\s*)?(?:\*\*)?(KEEP|DROP)\b(?:\*\*)?\s*(?:[:.\-—–]|$)/,
  /\b(Keep|Drop)\s*\([^)]{0,60}\)\s*\.?\s*$/,
  // Taxonomy-answering lines — the capture answering the fit-triage prompt's own classes
  // ("They are not a vendor, consulting firm, VC/PE firm, or job board.").
  /^\s*(?:\*\*)?\s*not any of the other categories/i,
  /\b(?:not|neither)\b[^.]{0,140}\b(?:vendor|consulting firm|consultancy|staffing|recruiting agency|VC\/PE|VC or PE|job board)\b[^.]{0,140}\b(?:vendor|consulting firm|consultancy|staffing|recruiting agency|VC\/PE|VC or PE|job board)\b/i,
];

// ---------------------------------------------------------------------------
// Over-strip guard (the worst failure this tool can commit).
//
// Analysts write finding and verdict in ONE sentence: "**Dana Rivera** — VP of
// Automation — DISQUALIFIES, route SKIP." Deleting that sentence deletes the only statement
// of the decisive fact, making the gold underivable and the *forbidden* answer inevitable
// (real fixtures were silently inverted this way). So a deletion unit carrying a PROPER
// NAME next to a TITLE is never silently deleted: the verdict clause is severed if it is
// cleanly separable, otherwise the unit STAYS and a BLOCKER tells the human to hand-trim.
// A fixture needing manual review beats an inverted one.
// ---------------------------------------------------------------------------
const TITLE_KEYWORD = /\b(VP|Vice President|Director|Chief|Head|Officer|President|CTO|CIO|CEO)\b/;

// Title/role vocabulary is capitalized too ("Senior Vice President of Data") — mask it so
// only an actual person-shaped bigram ("Dana Rivera") counts as a name.
const ROLE_WORDS =
  /\b(VP|SVP|EVP|Vice|President|Chief|Director|Head|Officer|Senior|Sr|Junior|Jr|Executive|Global|Group|Interim|Acting|Deputy|Lead|Manager|Engineering|Engineer|Technology|Technical|Information|Data|Product|Digital|Innovation|Analytics|Intelligence|Operations|Marketing|Security|Strategy|Science|Sciences|Research|Finance|Financial|People|Legal|Revenue|Growth|Design|Customer|Success|Business|Corporate|Enterprise|Platform|Software|Cloud|Machine|Learning|Automation|AI|ML|IT|CTO|CIO|CEO|CFO|COO|CDO|CPTO|CISO|The|A|An|And|Or|Of|At|For|In|On|No|Not|This|That|These|Those|Per|Same|Both|Real|Confirmed|Page|Title|Search|Company|Inc|LLC|Ltd|Corp|Co)\b/g;

const PROPER_NAME = /\b[A-Z][a-z][A-Za-z'’-]*\s+[A-Z][a-z][A-Za-z'’.-]*/;

const hasNamedPersonEvidence = (s: string) => TITLE_KEYWORD.test(s) && PROPER_NAME.test(s.replace(ROLE_WORDS, " "));

const isConclusionSentence = (s: string) => CONCLUSION_SENTENCE.some((re) => re.test(s));

// Softer than the strip list: patterns that HINT at the answer without being a
// conclusion sentence ("no SKIP trigger", "genuine zero"). Deleting these would take
// the findings with them, so they are flagged for the human instead of removed —
// the calibration step is a person, not a regex.
const RESIDUAL_LEAK =
  /\b(QUALIFIED|SKIP|FLAGGED|DROPPED)\b|\bdisqualif|\bgenuine zero\b|\bverdict\b|\bfalse[-_ ]positive|\bdrop[_ ]class\b/i;

function residualScan(text: string, why: string): string[] {
  const out: string[] = [];
  for (const line of text.split("\n"))
    if (RESIDUAL_LEAK.test(line)) out.push(`REVIEW (survived stripping${why ? `, ${why}` : ""}): ${line.trim().replace(/\s+/g, " ").slice(0, 160)}`);
  return out;
}

// Split a block into deletable units without reflowing: structural line breaks first
// (markdown headers, bullets, quotes, table rows — a run of capture-header comment lines
// is one "sentence" otherwise, and deleting it takes the whole preamble), then sentence
// boundaries. Concatenating the units reproduces the block byte for byte, so re-joining
// the survivors is the original minus exactly what was deleted.
function splitSentences(block: string): string[] {
  const lines = block.split("\n");
  const groups: string[] = [];
  let cur = "";
  lines.forEach((line, i) => {
    const nl = i < lines.length - 1 ? "\n" : "";
    if (cur && /^\s*(?:#{1,6}\s|[-*+]\s|>\s?|\||\d+\.\s)/.test(line)) { groups.push(cur); cur = ""; }
    cur += line + nl;
  });
  if (cur) groups.push(cur);
  return groups.flatMap((g) => g.split(/(?<=[.!?])(?=\s)/));
}

type StripResult = { text: string; removed: string[]; blockers: string[] };

const oneLine = (s: string, n = 160) => s.trim().replace(/\s+/g, " ").slice(0, n);

// "<evidence> — <conclusion>" → sever the trailing clause when the head alone is clean,
// still carries the name+title, and the tail is the conclusion. Deletion only: the head is
// returned byte-identical (plus the unit's trailing whitespace), never repunctuated.
function severVerdictClause(s: string): { head: string; clause: string } | null {
  const ws = s.match(/\s*$/)?.[0] ?? "";
  const body = s.slice(0, s.length - ws.length);
  const seps = [...body.matchAll(/\s+(?:[—–]|--)\s+/g)];
  for (let i = seps.length - 1; i >= 0; i--) {
    const at = seps[i].index ?? -1;
    if (at < 0) continue;
    const head = body.slice(0, at);
    const clause = body.slice(at);
    if (!isConclusionSentence(clause)) continue;      // the tail must BE the conclusion
    if (isConclusionSentence(head)) continue;         // …the head must be clean
    if (!hasNamedPersonEvidence(head)) continue;      // …and must still carry the evidence
    return { head: head + ws, clause };
  }
  return null;
}

// Strip conclusion sections/blocks/sentences. `mode` only narrows which section HEADERS
// count (see CONCLUSION_HEADER_SCRAPED); detection at block and sentence level is
// identical for analyst-authored and scraped/summarized text.
function stripConclusions(md: string, mode: StripMode = "analyst"): StripResult {
  const removed: string[] = [];
  const blockers: string[] = [];
  const headerRe = mode === "scraped" ? CONCLUSION_HEADER_SCRAPED : CONCLUSION_HEADER;
  const where = mode === "scraped" ? "scraped capture" : "analyst notes";
  const lines = md.split("\n");

  // 1. Section level: a header whose title names a conclusion kills the section,
  //    up to the next header of the same or higher level.
  const kept: string[] = [];
  let fence = false;
  let dropUntilLevel = 0;
  let secHeader = "";
  let secBody: string[] = [];
  const closeSection = () => {
    if (!secHeader) return;
    const whole = [secHeader, ...secBody];
    if (hasNamedPersonEvidence(whole.join("\n"))) {
      kept.push(...whole);
      blockers.push(
        `OVER-STRIP GUARD (${where}): the conclusion section "${oneLine(secHeader, 80)}" NAMES a person with a title, ` +
        `so it was KEPT rather than deleted — its evidence would have died with it. HAND-TRIM the verdict wording ` +
        `out of that section before promoting this fixture (it currently leaks the answer).`);
    } else {
      removed.push(`section: ${secHeader.trim()}`);
      for (const l of secBody) if (l.trim()) removed.push(`  section body: ${oneLine(l)}`);
    }
    secHeader = ""; secBody = [];
  };
  for (const line of lines) {
    if (/^\s*```/.test(line)) fence = !fence;
    const h = fence ? null : line.match(/^(#{1,6})\s+(.*)$/);
    if (h) {
      const level = h[1].length;
      if (dropUntilLevel && level <= dropUntilLevel) { closeSection(); dropUntilLevel = 0; }
      if (!dropUntilLevel && headerRe.test(h[2])) {
        dropUntilLevel = level;
        secHeader = line;
        continue;
      }
    }
    if (dropUntilLevel) { secBody.push(line); continue; }
    kept.push(line);
  }
  closeSection();

  // 2. Block level: a paragraph/bullet that OPENS with a conclusion marker goes whole.
  // 3. Sentence level: inside surviving blocks, drop only the conclusion sentences.
  const blocks = kept.join("\n").split(/\n(?=\s*\n)|\n\n/);
  const outBlocks: string[] = [];
  for (const block of blocks) {
    if (!block.trim()) { outBlocks.push(block); continue; }
    if (CONCLUSION_BLOCK_LEAD.test(block) && !hasNamedPersonEvidence(block)) {
      removed.push(`block: ${block.trim().split("\n")[0].slice(0, 120)}…`);
      continue;
    }
    const sentences = splitSentences(block);
    const survivors: string[] = [];
    for (const s of sentences) {
      if (!isConclusionSentence(s)) { survivors.push(s); continue; }
      if (hasNamedPersonEvidence(s)) {
        const cut = severVerdictClause(s);
        if (cut) {
          survivors.push(cut.head);
          removed.push(`clause (name+title kept, verdict clause only): ${oneLine(cut.clause)}`);
        } else {
          survivors.push(s);
          blockers.push(
            `OVER-STRIP GUARD (${where}): a conclusion sentence NAMES a person with a title and has no cleanly ` +
            `separable verdict clause, so it was KEPT rather than deleted — deleting it would delete the only ` +
            `statement of the evidence. HAND-TRIM it before promoting: "${oneLine(s)}"`);
        }
        continue;
      }
      removed.push(`sentence: ${oneLine(s)}`);
    }
    if (survivors.join("").trim()) outBlocks.push(survivors.join(""));
  }

  return { text: outBlocks.join("\n\n").replace(/\n{3,}/g, "\n\n").trimEnd() + "\n", removed, blockers };
}

// ---------------------------------------------------------------------------
// Hygiene: Apollo JSON trimming — name/title/seniority/last_refreshed_at + org
// name fields ONLY. Walks arbitrary nesting (enrichment captures nest person objects
// several levels down under per-query keys).
// ---------------------------------------------------------------------------
const PERSON_KEEP = ["name", "first_name", "last_name", "title", "headline", "seniority", "last_refreshed_at"];
const ORG_KEEP = ["name", "domain", "website_url", "primary_domain"];
const QUERY_META_KEYS = /^(_query|_capture|_meta)$/;

// Analyst annotation keys captured alongside a payload narrate the CONCLUSION ("BOTH matches
// name the vendor as a CLIENT, not adoption — false positive class"), which hands the model
// the gold. They are never source evidence, so they come out of EVERY staged JSON and are
// listed in the sidecar. `_query`/`_capture`/`_meta` are exempt: they carry provenance (and
// `_capture` may hold a transcribed payload itself).
const ANNOTATION_KEY = (k: string) =>
  (k.startsWith("_") && !QUERY_META_KEYS.test(k)) ||
  /^(note|notes|assessment|verdict|conclusion|rationale|bug_flag|company_object_note|capture_note)$/i.test(k);

// Drop annotation keys anywhere in a parsed JSON value, recording each path.
function stripAnnotations(value: any, dropped: Set<string>, path = ""): any {
  if (Array.isArray(value)) return value.map((v, i) => stripAnnotations(v, dropped, `${path}[${i}]`));
  if (!value || typeof value !== "object") return value;
  const out: Record<string, unknown> = {};
  for (const [k, v] of Object.entries(value)) {
    const p = path ? `${path}.${k}` : k;
    if (ANNOTATION_KEY(k)) { dropped.add(p); continue; }
    out[k] = stripAnnotations(v, dropped, p);
  }
  return out;
}

const isPersonish = (v: any) =>
  v && typeof v === "object" && !Array.isArray(v) &&
  ("title" in v || "seniority" in v) && ("first_name" in v || "name" in v || "last_name" in v);

function trimApollo(value: any, droppedKeys: Set<string>, path = ""): any {
  if (Array.isArray(value)) return value.map((v, i) => trimApollo(v, droppedKeys, `${path}[${i}]`));
  if (!value || typeof value !== "object") return value;

  if (isPersonish(value)) {
    const out: Record<string, unknown> = {};
    for (const k of PERSON_KEEP) if (k in value) out[k] = value[k];
    const org = value.organization ?? value.account;
    if (org && typeof org === "object") {
      const o: Record<string, unknown> = {};
      for (const k of ORG_KEEP) if (k in org) o[k] = org[k];
      out.organization = o;
    }
    for (const k of Object.keys(value)) if (!(k in out) && k !== "organization" && k !== "account")
      droppedKeys.add(`${path || "person"}.${k}`);
    return out;
  }

  const out: Record<string, unknown> = {};
  for (const [k, v] of Object.entries(value)) {
    // Analyst annotations captured alongside the payload are interpretation, not raw
    // evidence — drop them and say so in the sidecar. (`tech_titles_found` is names+titles —
    // SCHEMA.md's allowed evidence class — so it stays.)
    if (ANNOTATION_KEY(k)) { droppedKeys.add(`${path}.${k}`); continue; }
    if (/(^|_)(email|phone|apollo_contact_id|apollo_sequence_id|sanitized_phone|personal_emails|contact_emails)s?$/i.test(k)) {
      droppedKeys.add(`${path}.${k}`); continue;
    }
    out[k] = trimApollo(v, droppedKeys, path ? `${path}.${k}` : k);
  }
  return out;
}

// ---------------------------------------------------------------------------
// Hygiene: TheirStack payloads are multi-MB. Extract the company block for THIS
// domain plus its matching jobs — never copy the whole pull.
// ---------------------------------------------------------------------------
// Top-level shapes that occur under $PIPELINE_DATA/raw/theirstack/:
//   `data` + `metadata`            — the search_companies/search_jobs API envelope (most)
//   `jobs` (+ `_capture_note`)     — hand-transcribed per-domain job pulls
//   `results` + `query`            — the same, under the other transcription convention
//   `_capture.jobs`                — an inline transcription
// A bare top-level array is also supported.
const theirStackRows = (json: any): any[] => {
  for (const rows of [json?.data, json?.jobs, json?.results, json?._capture?.jobs, json])
    if (Array.isArray(rows)) return rows;
  return [];
};

// The per-domain `jobs`/`results` transcriptions carry NO domain field on their rows — the
// domain lives in the capture's provenance and in the filename. Such a capture is wholly
// about one company, so when nothing in it carries a domain at all we accept every row IF
// the domain is named in that provenance.
const DOMAINISH_FIELDS = ["domain", "company_domain", "possible_domains", "company"];
const namesDomain = (json: any, domain: string, source: string): boolean => {
  const hay: string[] = [source];
  const walk = (v: any, depth: number): void => {
    if (typeof v === "string") { hay.push(v); return; }
    if (depth > 2 || !v || typeof v !== "object" || Array.isArray(v)) return;
    for (const val of Object.values(v)) walk(val, depth + 1);
  };
  if (json && typeof json === "object" && !Array.isArray(json))
    for (const [k, v] of Object.entries(json)) { hay.push(k); if (!Array.isArray(v)) walk(v, 0); }
  const dl = domain.toLowerCase();
  return hay.some((s) => typeof s === "string" && s.toLowerCase().includes(dl));
};

function extractTheirStack(
  json: any, domain: string, opts: { source?: string; dropped?: Set<string> } = {},
): any | null {
  const dl = domain.toLowerCase();
  const rows = theirStackRows(json);
  const matches = (e: any) => {
    const cands = [e?.domain, e?.company_domain, e?.company?.domain, ...(Array.isArray(e?.possible_domains) ? e.possible_domains : [])];
    return cands.some((c) => typeof c === "string" && c.toLowerCase() === dl);
  };
  const anyDomainField = rows.some((e) => e && typeof e === "object" &&
    DOMAINISH_FIELDS.some((f) => e[f] !== undefined && e[f] !== null));
  const wholeFile = rows.length > 0 && !anyDomainField && namesDomain(json, domain, opts.source ?? "");
  const hits = (wholeFile ? rows : rows.filter(matches)).map((e) => {
    const { apollo_id, logo, ...rest } = e ?? {}; // apollo_id is a 24-hex id; logo is a data URI/asset
    return rest;
  });
  if (!hits.length) return null;
  const dropped = opts.dropped ?? new Set<string>();
  for (const k of Object.keys(json ?? {})) if (ANNOTATION_KEY(k)) dropped.add(k);
  const block = stripAnnotations({ metadata: json?.metadata ?? json?.query ?? null, data: hits }, dropped, "");
  return {
    ...block,
    _excerpt: wholeFile
      ? `single-company capture for ${domain} (rows carry no domain field; domain confirmed from the capture's own provenance) — ${hits.length} row(s), nothing removed`
      : `company block for ${domain} only — ${rows.length - hits.length} other companies removed`,
  };
}

