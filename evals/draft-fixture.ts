// Raw-pointer classification
// ---------------------------------------------------------------------------
type Pointer = {
  pointer: string;      // store-relative path as written in raw_pointers
  abs: string;
  exists: boolean;
  kind: "theirstack" | "posting" | "firecrawl" | "apollo" | "salesnav" | "other";
  slug: string;         // filename without the date prefix/extension
  isHomepage: boolean;
  isLeadership: boolean;
  isSweep: boolean;
};

function classify(pointer: string): Pointer {
  const abs = dataPath(pointer);
  const file = basename(pointer);
  const slug = file.replace(/^\d{4}-\d{2}-\d{2}-/, "").replace(/\.(json|md|txt)$/i, "");
  const kind: Pointer["kind"] =
    pointer.startsWith("raw/theirstack/") ? "theirstack" :
    pointer.startsWith("raw/postings/") ? "posting" :
    pointer.startsWith("raw/firecrawl/") ? "firecrawl" :
    pointer.startsWith("raw/apollo/") ? "apollo" :
    pointer.startsWith("raw/salesnav/") ? "salesnav" : "other";
  return {
    pointer, abs, exists: existsSync(abs), kind, slug,
    isHomepage: /homepage|home$/i.test(slug),
    isLeadership: /team|leadership|about|people|exec|management/i.test(slug),
    // M2 captures the people sweep as `<date>-people.json` or `<date>-q1|q2|q3.json` per query.
    isSweep: kind === "apollo" && /sweep|people|leadership|roster|(^|-)q[1-9]$/i.test(slug),
  };
}

// ---------------------------------------------------------------------------
// Input builders — each returns the bytes to stage plus the trim log.
// ---------------------------------------------------------------------------
type Staged = {
  name: string;               // filename under inputs/
  role: string;
  bytes: string;
  source: string;             // provenance: store-relative pointer
  removed: string[];          // conclusion strips
  droppedKeys: string[];      // JSON keys removed by structural trimming
  redactions: Record<string, number>;
  blockers: string[];         // over-strip guard hits — manual trimming required
  oversize?: boolean;
};

// Conclusion detection runs over EVERY text input. Scraped/summarized captures are not
// innocent: summaries end with "Keep (operating company).", carry "## Verdict" sections and
// "CONCLUSION:" lines, and answer the fit-triage taxonomy outright. What differs is only
// which section headers count (see stripConclusions).
function stageMarkdown(p: Pointer, role: string, name: string, analystAuthored: boolean): Staged {
  const raw = readFileSync(p.abs, "utf8");
  const mode: StripMode = analystAuthored ? "analyst" : "scraped";
  const stripped = stripConclusions(raw, mode);
  const { text, hits } = redact(stripped.text);
  const staged: Staged = {
    name, role, bytes: text, source: p.pointer, removed: stripped.removed, droppedKeys: [], redactions: hits,
    blockers: stripped.blockers.map((b) => `inputs/${name}: ${b}`),
  };
  staged.removed.push(...residualScan(text, analystAuthored ? "" : "scraped source"));
  return staged;
}

function stageApollo(p: Pointer, role: string, name: string): Staged {
  const dropped = new Set<string>();
  const trimmed = trimApollo(JSON.parse(readFileSync(p.abs, "utf8")), dropped);
  const { text, hits } = jsonBytes(trimmed);
  return { name, role, bytes: text, source: p.pointer, removed: residualScan(text, ""), droppedKeys: [...dropped], redactions: hits, blockers: [] };
}

function stageTheirStack(p: Pointer, domain: string, role: string, name: string): Staged | null {
  const dropped = new Set<string>();
  const block = extractTheirStack(JSON.parse(readFileSync(p.abs, "utf8")), domain, { source: p.pointer, dropped });
  if (!block) return null;
  const { text, hits } = jsonBytes(block);
  return {
    name, role, bytes: text, source: p.pointer, removed: residualScan(text, ""),
    droppedKeys: ["(whole-pull rows for other companies)", "apollo_id", "logo", ...dropped], redactions: hits, blockers: [],
  };
}

// The per-domain Sales Navigator queue checklist (named execs + absence claims to confirm):
// one bullet block in queue/salesnav-pending.md. The surrounding batch narrative states
// the outcome, so only the domain's own bullet is extracted.
function extractChecklist(domain: string): { text: string; removed: string[]; blockers: string[] } | null {
  const p = dataPath("queue", "salesnav-pending.md");
  if (!existsSync(p)) return null;
  const lines = readFileSync(p, "utf8").split("\n");
  const start = lines.findIndex((l) => new RegExp(`^-\\s+${domain.replace(/\./g, "\\.")}\\b`, "i").test(l));
  if (start < 0) return null;
  const out = [lines[start]];
  for (let i = start + 1; i < lines.length; i++) {
    if (/^\S/.test(lines[i]) || /^-\s/.test(lines[i])) break;
    if (!lines[i].trim() && !out[out.length - 1].trim()) break;
    out.push(lines[i]);
  }
  const stripped = stripConclusions(out.join("\n").trimEnd() + "\n");
  return {
    text: `# Sales Navigator queue checklist — ${domain}\n\n${stripped.text}`,
    removed: stripped.removed,
    blockers: stripped.blockers.map((b) => `inputs/checklist.md: ${b}`),
  };
}

// ---------------------------------------------------------------------------
// Task inference + per-task input selection
// ---------------------------------------------------------------------------
type Ctx = { domain: string; account: any; pointers: Pointer[]; evidenceMd: string | null; dropClasses: DropClass[] };

function inferTasks(ctx: Ctx): string[] {
  const tasks: string[] = [];
  const has = (fn: (p: Pointer) => boolean) => ctx.pointers.some((p) => p.exists && fn(p));
  if (has((p) => p.kind === "salesnav")) tasks.push("salesnav-verdict");
  if (has((p) => p.isSweep)) tasks.push("route");
  if (has((p) => p.kind === "theirstack") && has((p) => p.kind === "firecrawl" && p.isHomepage)) tasks.push("fit-triage");
  if (ctx.evidenceMd) tasks.push("evidence-synthesis");
  return tasks;
}

function buildInputs(task: string, ctx: Ctx): { staged: Staged[]; blockers: string[] } {
  const staged: Staged[] = [];
  const blockers: string[] = [];
  const live = ctx.pointers.filter((p) => p.exists);
  const first = (fn: (p: Pointer) => boolean) => live.find(fn);

  const posting = first((p) => p.kind === "posting");
  const homepage = first((p) => p.kind === "firecrawl" && p.isHomepage);
  const leadership = first((p) => p.kind === "firecrawl" && p.isLeadership && !p.isHomepage);
  const theirstack = live.filter((p) => p.kind === "theirstack");
  const sweeps = live.filter((p) => p.isSweep);
  const salesnav = first((p) => p.kind === "salesnav");

  const addMd = (p: Pointer | undefined, role: string, name: string, analyst: boolean) => {
    if (p) staged.push(stageMarkdown(p, role, name, analyst));
  };
  const addTheirStack = (role: string, name: string): boolean => {
    for (const p of theirstack) {
      const s = stageTheirStack(p, ctx.domain, role, name);
      if (s) { staged.push(s); return true; }
    }
    return false;
  };
  // Every sweep capture is staged under the same role — the loader only checks presence, and
  // a per-query capture set (q1/q2/q3) IS the sweep the router saw.
  const addSweeps = () => {
    for (const s of sweeps) staged.push(stageApollo(s, "apollo_sweep", sweeps.length === 1 ? "apollo-sweep.json" : `apollo-${s.slug}.json`));
  };

  if (task === "fit-triage") {
    if (!addTheirStack("theirstack_company", "theirstack-company.json"))
      blockers.push("REQUIRED role `theirstack_company`: no TheirStack capture in raw_pointers contains a company block for this domain — extract by hand.");
    addMd(homepage, "homepage", "homepage.md", false);
    addMd(posting, "jd_text", "posting.md", true);
  }

  if (task === "route") {
    if (sweeps.length) addSweeps();
    else blockers.push("REQUIRED role `apollo_sweep`: no Apollo people/sweep capture in raw_pointers.");
    addMd(salesnav, "salesnav", "salesnav-notes.md", true);
    addMd(leadership, "firecrawl_leadership", "firecrawl-leadership.md", false);
    addMd(posting, "posting", "posting.md", true);
  }

  if (task === "salesnav-verdict") {
    if (salesnav) addMd(salesnav, "salesnav", "salesnav-notes.md", true);
    else blockers.push("REQUIRED role `salesnav`: no raw/salesnav capture in raw_pointers.");
    const cl = extractChecklist(ctx.domain);
    if (cl) {
      const r = redact(cl.text);
      staged.push({ name: "checklist.md", role: "checklist", bytes: r.text, source: "queue/salesnav-pending.md (per-domain bullet)", removed: cl.removed, droppedKeys: [], redactions: r.hits, blockers: cl.blockers });
    }
    else blockers.push("REQUIRED role `checklist`: no per-domain bullet found in queue/salesnav-pending.md — write the pre-pass checklist (named execs, absence claims) by hand from the run record.");
    addSweeps();
  }

  if (task === "evidence-synthesis") {
    // The full per-domain raw set as captured — this task's whole point is breadth.
    for (const p of live.filter((x) => x.kind === "posting"))
      staged.push(stageMarkdown(p, "posting", `posting-${p.slug}.md`, true));
    for (const p of live.filter((x) => x.kind === "firecrawl"))
      staged.push(stageMarkdown(p, `firecrawl_${p.slug.replace(/[^a-z0-9]+/gi, "_")}`, `firecrawl-${p.slug}.md`, false));
    for (const p of live.filter((x) => x.kind === "apollo"))
      staged.push(stageApollo(p, `apollo_${p.slug.replace(/[^a-z0-9]+/gi, "_")}`, `apollo-${p.slug}.json`));
    for (const p of live.filter((x) => x.kind === "salesnav"))
      staged.push(stageMarkdown(p, "salesnav", "salesnav-notes.md", true));
    addTheirStack("theirstack_company", "theirstack-company.json");
  }

  // Over-strip guard hits are BLOCKERs like any missing role: the fixture is not
  // promotable until a human hand-trims the conclusion the guard refused to delete.
  for (const s of staged) blockers.push(...s.blockers);

  return { staged, blockers };
}

// ---------------------------------------------------------------------------
// Gold prefill — from the CORRECTED account.yaml (post-review state), which is
// exactly what SCHEMA.md defines gold to be. Every prefill is explained in notes
// so the reviewer can verify rather than trust.
// ---------------------------------------------------------------------------

// Best-effort guess of the drop class from the evidence note, scored by how many of the
// class's slug tokens and description words appear in the note. The classes come from
// config/icp.md at run time — nothing here knows their names. "TODO" when nothing matches.
const STOPWORDS = new Set(["of", "or", "the", "and", "a", "an", "to", "not", "our", "we", "for", "with", "that", "than"]);
export function guessDropClass(note: string, classes: DropClass[]): string {
  const hay = ` ${note.toLowerCase().replace(/[^a-z0-9]+/g, " ")} `;
  const has = (w: string) => hay.includes(` ${w} `) || hay.includes(` ${w}s `) || hay.includes(` ${w.replace(/s$/, "")} `);
  let best: { slug: string; score: number } | null = null;
  for (const c of classes) {
    const slugWords = c.slug.split("_").filter((w) => w.length > 2 && !STOPWORDS.has(w));
    const descWords = c.description.toLowerCase().split(/[^a-z]+/).filter((w) => w.length >= 6 && !STOPWORDS.has(w));
    const score = slugWords.filter(has).length * 2 + descWords.filter(has).length;
    if (score > 0 && (!best || score > best.score)) best = { slug: c.slug, score };
  }
  return best?.slug ?? "TODO";
}

function prefillGold(task: string, ctx: Ctx): { gold: Record<string, unknown> | null; notes: string[] } {
  const a = ctx.account;
  const notes: string[] = [];
  const note = (s: string) => { notes.push(s); };

  if (task === "fit-triage") {
    const decision = a.status === "dropped" ? "drop" : "keep";
    note(`gold.decision="${decision}" ← account.status="${a.status}" (dropped ⇒ drop, anything else ⇒ the account survived triage).`);
    if (decision === "drop") {
      const recorded = typeof a.drop_class === "string" && a.drop_class.trim() ? a.drop_class.trim() : null;
      const cls = recorded ?? guessDropClass(String(a.evidence_note ?? ""), ctx.dropClasses);
      note(recorded
        ? `gold.drop_class="${cls}" ← account.drop_class. Verify it is still a slug listed under "## Drop classes" in config/icp.md.`
        : `gold.drop_class="${cls}" ← GUESSED by keyword match of the config/icp.md drop classes over evidence_note. VERIFY — this is the one field the scaffolder cannot know.`);
      return { gold: { decision, drop_class: cls }, notes };
    }
    note("A keep carries no drop_class.");
    return { gold: { decision }, notes };
  }

  if (task === "route") {
    const route = a.route ?? a.provisional_route ?? "TODO";
    note(`gold.route="${route}" ← account.${a.route ? "route" : a.provisional_route ? "provisional_route (NO final route yet — this account is not settled; consider waiting for the Sales Navigator pass before promoting)" : "route (ABSENT — fill by hand)"}.`);
    if (!a.route && a.provisional_route) note("WARNING: provisional route used as gold. Gold must be the POST-correction state (SCHEMA.md) — a provisional route is by definition pre-verification.");
    note("gold.evidence_names is a SECONDARY (reported, ungated) field left empty on purpose — fill it with the people whose titles/scope decide the classification, or delete the key.");
    return { gold: { route, evidence_names: [] }, notes };
  }

  if (task === "salesnav-verdict") {
    const route = String(a.route ?? a.provisional_route ?? "");
    const verdict = route === "SKIP" ? "flip_to_skip" : (route === "FLAGGED" || a.status === "flagged") ? "flag" : "confirm";
    note(`gold.verdict="${verdict}" ← INFERRED from account.route="${a.route ?? "—"}", verification="${a.verification ?? "—"}", status="${a.status}": SKIP ⇒ flip_to_skip, FLAGGED/flagged ⇒ flag, otherwise the pass confirmed the provisional call.`);
    note("VERIFY the inference: 'confirm' is only right if the Sales Navigator pass upheld the headless route. A pass that corrected the evidence without changing the route still reads as 'confirm' here — check the notes' own history.");
    note("gold.evidence_names is a SECONDARY (reported, ungated) field left empty on purpose — fill it with the people whose titles/scope actually decide the verdict, or delete the key.");
    return { gold: { verdict, evidence_names: [] }, notes };
  }

  if (task === "evidence-synthesis") {
    note("evidence-synthesis is rubric-scored: `rubric` replaces `gold` (SCHEMA.md). The must/should checks below are placeholders — write them from the historical evidence.md staged as REFERENCE-evidence.md in this dir.");
    note("Each check must be a single verifiable statement a judge can pass/fail against the produced evidence.md. `must` gates must_pass_rate; `should` is reported only.");
    return { gold: null, notes };
  }

  return { gold: {}, notes };
}

function inferIncidentDate(account: any): string | undefined {
  const note = String(account.evidence_note ?? "");
  const near = note.match(/\b(?:correct(?:ed|ion)|reversed|mis-?drop(?:ped)?)\b[^.]{0,80}?(\d{4}-\d{2}-\d{2})/i)
    ?? note.match(/(\d{4}-\d{2}-\d{2})[^.]{0,40}\b(?:correct|reversed|mis-?drop)/i);
  if (near) return near[1];
  return account.routed_at ?? account.triaged_at ?? undefined;
}

