const slugify = (s: string) => s.toLowerCase().replace(/[^a-z0-9]+/g, "_").replace(/^_+|_+$/g, "");

function writeFixtureYaml(dir: string, fixture: Record<string, unknown>, comments: Record<string, string>): void {
  const doc = new YAML.Document(fixture);
  for (const [key, text] of Object.entries(comments)) {
    const pair: any = (doc.contents as any)?.items?.find((p: any) => String(p.key?.value ?? p.key) === key);
    if (pair?.key) pair.key.commentBefore = text;
  }
  // The loader requires provenance.incident_date to be a STRING; an unquoted YAML date is
  // a timestamp under any schema that enables the tag. Quote it so it can never drift.
  const prov: any = (doc.contents as any)?.items?.find((p: any) => String(p.key?.value) === "provenance")?.value;
  const inc: any = prov?.items?.find((p: any) => String(p.key?.value) === "incident_date");
  if (inc?.value) inc.value.type = "QUOTE_DOUBLE";

  const out = String(doc);
  const back = YAML.parse(out); // fail loud here rather than at load time
  if (back.provenance?.incident_date !== undefined && typeof back.provenance.incident_date !== "string")
    throw new Error("incident_date did not round-trip as a string");
  writeFileSync(join(dir, "fixture.yaml"), out);
}

